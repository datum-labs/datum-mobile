import {
  autoStepForRange,
  computeChartStep,
  firstSeriesPoints,
  formatBytes,
  formatCores,
  formatCount,
  formatDurationFromMs,
  formatMs,
  formatPercent,
  formatRps,
  formatShortNumber,
  lastValue,
  metricRangePreset,
  parseDurationToMs,
  resolveMetricWindow,
  scalarValue,
  splitUnit,
  toMetricSeries,
  valuesByLabel,
  type PromResponse,
} from '..';

// Trimmed from real staging gateway responses (VictoriaMetrics).
const matrix: PromResponse = {
  status: 'success',
  data: {
    resultType: 'matrix',
    result: [
      {
        metric: {},
        values: [
          [1791838800, '0'],
          [1791838860, '0.03333333333333333'],
          [1791838920, 'NaN'],
          [1791838980, '+Inf'],
          [1791839040, '649.9999999999993'],
        ],
      },
    ],
  },
};

const byOutcome: PromResponse = {
  status: 'success',
  data: {
    resultType: 'vector',
    result: [
      { metric: { coraza_outcome: 'allowed' }, value: [1791842414, '6780'] },
      { metric: { coraza_outcome: 'blocked' }, value: [1791842414, '12'] },
      { metric: { coraza_outcome: 'dropped' }, value: [1791842414, 'NaN'] },
    ],
  },
};

describe('toMetricSeries', () => {
  test('flattens a matrix, dropping NaN and Inf samples', () => {
    expect(toMetricSeries(matrix)).toEqual([
      {
        labels: {},
        points: [
          { t: 1791838800, v: 0 },
          { t: 1791838860, v: 0.03333333333333333 },
          { t: 1791839040, v: 649.9999999999993 },
        ],
      },
    ]);
    expect(lastValue(firstSeriesPoints(matrix))).toBe(649.9999999999993);
  });

  test('vector results become one-point series', () => {
    expect(toMetricSeries(byOutcome)[0]).toEqual({ labels: { coraza_outcome: 'allowed' }, points: [{ t: 1791842414, v: 6780 }] });
    expect(valuesByLabel(byOutcome, 'coraza_outcome')).toEqual({ allowed: 6780, blocked: 12 });
  });

  test('scalar results', () => {
    expect(scalarValue({ status: 'success', data: { resultType: 'scalar', result: [1, '42'] } })).toBe(42);
  });

  test('empty and missing data', () => {
    const empty: PromResponse = { status: 'success', data: { resultType: 'matrix', result: [] } };
    expect(toMetricSeries(empty)).toEqual([]);
    expect(firstSeriesPoints(empty)).toEqual([]);
    expect(scalarValue(empty)).toBeNull();
    expect(toMetricSeries(undefined)).toEqual([]);
    expect(toMetricSeries({ status: 'error', error: 'bad' })).toEqual([]);
    expect(valuesByLabel(empty, 'x')).toEqual({});
  });
});

// Expected output generated by the portal's formatValue and the compute UI's
// formatBytes / formatCores with the same inputs.
describe('formatters', () => {
  test('milliseconds-auto', () => {
    expect([0.4, 12.6, 999, 1000, 2345].map((v) => formatMs(v))).toEqual(['0ms', '13ms', '999ms', '1.00s', '2.35s']);
  });
  test('percent', () => {
    expect([0, 0.0123, 0.5].map((v) => formatPercent(v))).toEqual(['0.00%', '1.23%', '50.00%']);
  });
  test('requests per second', () => {
    expect([0, 0.0333, 12.5].map((v) => formatRps(v))).toEqual(['0.00 req/s', '0.03 req/s', '12.50 req/s']);
  });
  test('short numbers', () => {
    expect([0, 12, 999, 1234, 2_500_000].map((v) => formatShortNumber(v, 0))).toEqual(['0', '12', '999', '1K', '3M']);
    expect(formatShortNumber(1234, 1)).toBe('1.2K');
    expect(formatShortNumber(0.5)).toBe('0.5');
  });
  test('bytes', () => {
    expect([0, 512, 20148224, 3 * 1024 ** 3].map(formatBytes)).toEqual(['0 B', '512 B', '19 MB', '3.0 GB']);
  });
  test('cores', () => {
    expect([0, 0.001, 0.0072, 0.12345, 1.256, 2, 150].map(formatCores)).toEqual([
      '0',
      '<0.01',
      '0.01',
      '0.12',
      '1.26',
      '2',
      '150',
    ]);
    expect(formatCores(Number.NaN)).toBe('—');
  });
  test('counts', () => {
    expect(formatCount(4104.4)).toBe((4104).toLocaleString());
  });
  test('splitUnit', () => {
    expect(splitUnit('12.50 req/s')).toEqual({ value: '12.50', unit: 'req/s' });
    expect(splitUnit('13ms')).toEqual({ value: '13', unit: 'ms' });
    expect(splitUnit('1.23%')).toEqual({ value: '1.23', unit: '%' });
    expect(splitUnit('<0.01')).toEqual({ value: '<0.01', unit: '' });
    expect(splitUnit('19 MB')).toEqual({ value: '19', unit: 'MB' });
    expect(splitUnit('—')).toEqual({ value: '—', unit: '' });
  });
});

describe('time ranges and steps', () => {
  test('autoStepForRange matches the portal', () => {
    const minutes = [15, 60, 360, 1440, 10080];
    expect(minutes.map((m) => autoStepForRange(m * 60_000))).toEqual(['15s', '1m', '15m', '1h', '1h']);
    expect(autoStepForRange(0)).toBe('1m');
    expect(autoStepForRange(Number.NaN)).toBe('1m');
  });

  test('computeChartStep matches the compute UI', () => {
    expect([60, 360, 1440].map((m) => computeChartStep(m * 60_000))).toEqual(['15s', '54s', '3m']);
  });

  test('durations', () => {
    expect(formatDurationFromMs(metricRangePreset('1h').durationMs)).toBe('1h');
    expect(formatDurationFromMs(metricRangePreset('7d').durationMs)).toBe('7d');
    expect(formatDurationFromMs(90_000)).toBe('1m');
    expect(parseDurationToMs('15s')).toBe(15_000);
    expect(parseDurationToMs('2h')).toBe(7_200_000);
    expect(parseDurationToMs('soon')).toBeNull();
  });

  test('windows end now, in unix seconds', () => {
    expect(resolveMetricWindow('15m', 1_791_842_400_500)).toEqual({ start: 1_791_841_500, end: 1_791_842_400 });
  });
});
